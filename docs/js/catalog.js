// Compute world-space coordinates (in mm, printer base sits on Y=0, X centered at 0, Z centered at 0)
// Note: Right-handed Y-up 3D viewport coordinates (X = left/right, Y = up, Z = front/back)
export function getHardpointPose(printer, hardpointId, toolheadPos = { x: 0, y: 0, z: 0 }) {
  const ox = printer.outerSize.x;
  const oy = printer.outerSize.z; // outer height
  const oz = printer.outerSize.y; // outer depth
  const bx = printer.buildVolume.x;
  const bz = printer.buildVolume.y;
  const bedY = printer.frameType === 'cube' ? oy * 0.36 : 95;
  const thX = toolheadPos.x;
  const thY = bedY + 52 + toolheadPos.y;
  const thZ = toolheadPos.z;
  const hx = ox * 0.5;
  const hz = oz * 0.5;

  switch (hardpointId) {
    case 'toolhead-front':  return { pos: [thX, thY + 8, thZ + 38],   rot: [0, 0, 0] };
    case 'toolhead-side':   return { pos: [thX + 38, thY + 8, thZ],   rot: [0, 90, 0] };
    case 'toolhead-top':    return { pos: [thX, thY + 56, thZ],       rot: [0, 0, 0] };
    case 'x-carriage':      return { pos: [thX, thY + 12, thZ - 32],  rot: [0, 180, 0] };
    case 'bed-edge':        return { pos: [bx * 0.45, bedY + 8, bz * 0.48], rot: [0, 0, 0] };
    case 'gantry-left':     return { pos: [-hx + 28, thY + 15, thZ],  rot: [0, 90, 0] };
    case 'frame-top-front': return { pos: [0, oy - 12, hz - 10],      rot: [0, 0, 0] };
    case 'frame-left-post': return { pos: [-hx - 14, oy * 0.58, 0],   rot: [0, -90, 0] };
    case 'frame-right-post':return { pos: [hx + 14, oy * 0.58, 0],    rot: [0, 90, 0] };
    case 'frame-rear':      return { pos: [0, oy * 0.62, -hz - 14],   rot: [0, 180, 0] };
    case 'frame-front-bot': return { pos: [0, 42, hz + 18],           rot: [-35, 0, 0] };
    case 'enclosure-roof':  return { pos: [0, oy + 18, 0],            rot: [0, 0, 0] };
    default:                return { pos: [thX, thY + 25, thZ + 40],  rot: [0, 0, 0] };
  }
}
